test('closure: freezes the 23-row ledger with honest summary counts', () => {
  assert.equal(Object.isFrozen(CLOSURE_CAPABILITY_LEDGER), true);
  assert.equal(CLOSURE_CAPABILITY_LEDGER.length, 23);
  for (const entry of CLOSURE_CAPABILITY_LEDGER) {
    assert.equal(Object.isFrozen(entry), true);
    assert.equal(Object.isFrozen(entry.evidencePaths), true);
    assert.ok(entry.title.length > 0 && entry.closureCriterion.length > 0 && entry.residualBoundary.length > 0);
    assert.ok(entry.evidencePaths.length >= 1);
    if (entry.evidenceLevel !== 'unprovisioned_external') assert.equal(entry.verificationStatus, 'passed');
    else assert.ok(entry.disposition !== 'closed_local' || entry.unlockPrerequisite !== null || entry.verificationStatus !== 'passed');
  }
  const ids = new Set(CLOSURE_CAPABILITY_LEDGER.map(entry => entry.id));
  assert.equal(ids.size, 23);
  assert.equal(CLOSURE_CAPABILITY_LEDGER.filter(entry => entry.disposition === 'closed_local').length, 18);
  assert.equal(CLOSURE_CAPABILITY_LEDGER.filter(entry => entry.evidenceLevel === 'unprovisioned_external').length, 5);
  const external = CLOSURE_CAPABILITY_LEDGER.filter(entry => entry.evidenceLevel === 'unprovisioned_external');
  for (const entry of external) { assert.notEqual(entry.verificationStatus, 'passed'); assert.ok(entry.unlockPrerequisite !== null && entry.unlockPrerequisite.length > 0); }
});
